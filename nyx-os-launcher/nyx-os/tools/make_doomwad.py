#!/usr/bin/env python3
"""Generate user/doom/nyx_wad.h: the shareware IWAD as a C byte array.

Usage: python3 tools/make_doomwad.py <doom1.wad> [out-header]
Validates the IWAD magic before embedding.  The array is aligned and
marked unused so gcc emits it into .rodata verbatim.
"""
import sys, os

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "host-files/doom1.wad"
    out = sys.argv[2] if len(sys.argv) > 2 else "user/doom/nyx_wad.h"
    data = open(src, "rb").read()
    if data[:4] != b"IWAD":
        sys.exit(f"{src}: not an IWAD (magic {data[:4]!r})")
    print(f"embedding {src}: {len(data)} bytes")
    lines = []
    lines.append("// AUTO-GENERATED by tools/make_doomwad.py — DO NOT EDIT")
    lines.append("// DOOM shareware IWAD (id Software, doom1.wad 1.9)")
    lines.append("#ifndef NYX_WAD_H")
    lines.append("#define NYX_WAD_H")
    lines.append("#include <stdint.h>")
    lines.append("#include <stddef.h>")
    lines.append(f"static const unsigned int nyx_wad_size = {len(data)};")
    lines.append(
        '__attribute__((aligned(4096), used))\n'
        'static const uint8_t nyx_wad_bytes[] = {')
    CH = 20
    for i in range(0, len(data), CH):
        chunk = data[i:i+CH]
        lines.append("    " + ",".join(str(b) for b in chunk) + ",")
    lines.append("};")
    lines.append("#endif // NYX_WAD_H")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")

if __name__ == "__main__":
    main()
