#!/usr/bin/env python3
"""tools/embed-userprogs.py — embed the built ring-3 user ELFs into the
kernel as byte arrays (mirrors tools/embed-files.py).  Run by the
Makefile after user/*.elf are linked; emits cpu/userprogs.c."""

import os

# Programs in build order; index 0 = `user`, index 1 = `userfault`,
# index 2 = `sockget` (ring-3 BSD-socket HTTP demo).
PROGS = ["hello", "fault", "sockget"]


def hex_row(data: bytes) -> str:
    return ",".join("0x%02x" % b for b in data)


def generate() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    base = os.path.normpath(os.path.join(here, "..", "user"))
    out = os.path.normpath(os.path.join(here, "..", "cpu", "userprogs.c"))

    L = []
    L.append("// cpu/userprogs.c — Auto-generated. Do not edit.")
    L.append("// Generated by: tools/embed-userprogs.py")
    L.append("#include <stdint.h>")
    L.append("#include <userprogs.h>")
    L.append("")
    for name in PROGS:
        path = os.path.join(base, name + ".elf")
        raw = open(path, "rb").read()
        L.append("static const unsigned char _up_%s[%d] = {" % (name, len(raw)))
        for i in range(0, len(raw), 12):
            L.append("  " + hex_row(raw[i:i + 12]) + ",")
        L.append("};")
        L.append("")
    L.append("const userprog_t userprogs[] = {")
    for name in PROGS:
        L.append('  { "%s", _up_%s, sizeof(_up_%s) },' % (name, name, name))
    L.append("};")
    L.append("const int userprog_count = %d;" % len(PROGS))
    L.append("")

    with open(out, "w") as fh:
        fh.write("\n".join(L))
    print("Embedded %d user programs -> %s" % (len(PROGS), out))


if __name__ == "__main__":
    generate()
