// include/fs.h
#ifndef FS_H
#define FS_H

// 127 file slots (up from 31 — the previous 31-slot budget was
// exhausted by the ~27 host-files packed at build time, leaving only
// ~4 slots for user files/folders, which triggered "Filesystem full!"
// almost immediately).  The on-disk data region ends exactly where
// the desktop icon-layout sector lives (see ICON_LAYOUT_SECTOR in
// cpu/desktop.c), which is derived from MAX_FILES so it always sits
// OUTSIDE the filesystem data area and fs_save_to_disk() can never
// overwrite it.
#define MAX_FILES    127
#define MAX_FILENAME 32
#define MAX_FILESIZE (16*1024*1024)   // 16 MiB — per-file allocation ceiling
// With dynamic allocation, each file only uses as much heap as its
// actual content size (up to MAX_FILESIZE).  BSS is ~6 KB for the
// File[] array + pointers; all content lives on the heap.

typedef struct {
    char  name[MAX_FILENAME];
    char* content;       // heap-allocated content buffer (NULL if unused)
    int   content_cap;   // allocated capacity of content[] (bytes)
    int   used;
    int   size;          // byte count of content (0 = use strlen)
} File;

extern File filesystem[MAX_FILES];
extern int  file_count;

// Allocate or resize the content buffer for file slot `i`.
// content_cap tracks the heap allocation; size tracks logical length.
void file_content_alloc(int i, int min_cap);
void file_content_free(int i);

// On-disk layout constants — single source of truth.  cpu/fs.c uses
// them to read/write the disk; cpu/desktop.c uses the derived
// FS_ICON_LAYOUT_SECTOR so the desktop-state sector always sits at a
// fixed, collision-free location in front of the growing data region.
//
// v7 (NYXFS002) — AUTO-GROW layout.  Files are no longer pinned to
// fixed per-slot regions (that forced a 133 MB pre-sized image even
// with 8 tiny files).  Instead each directory entry records its
// file's absolute start sector (start_lba) + length, and every save
// rewrites all used files compactly, one after another, starting at
// FS_DATA_START.  The on-disk image is exactly as big as the data
// that exists, and QEMU's raw driver extends the file automatically
// when a write lands past the current end — so capacity scales by
// simply writing further into the image.  No pre-sized maximum and
// no re-running migration tools when constants change.
#define FS_SB_SECTOR        0
#define FS_DIR_SECTOR       1
#define FS_DIR_ENTRY_SZ     44          // 32 (name) + 4 (used) + 4 (size) + 4 (start_lba)
#define FS_DIR_SECTORS      ((MAX_FILES * FS_DIR_ENTRY_SZ + 511) / 512)  // 11
#define FS_ICON_LAYOUT_SECTOR (FS_SB_SECTOR + 1 + FS_DIR_SECTORS)        // 12 — fixed
#define FS_DATA_START       (FS_ICON_LAYOUT_SECTOR + 1)                  // 13 — data frontier

// Persist the in-RAM filesystem[] array to disk, or load it back.
// Both are safe no-ops if no ATA disk was detected at boot (e.g.
// QEMU launched without -hda) — the OS still works exactly as
// before in that case, just without persistence across reboots.
int fs_save_to_disk(void);
int fs_load_from_disk(void);

// Load files embedded at compile time into the kernel ELF
// (generated by tools/embed-files.py into cpu/embedded_fs.c).
// Always safe to call — a no-op when no files were embedded.
void fs_load_embedded(void);

#endif
