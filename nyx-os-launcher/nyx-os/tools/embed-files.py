#!/usr/bin/env python3
"""
embed-files.py — Embed host files into Nyx OS kernel at compile time.

Reads all files from host-files/ (skipping README) and generates
cpu/embedded_fs.c — a C source file with exact-size byte arrays that
gets compiled directly into the kernel ELF.  No ATA disk needed.
No zero-padding — each file occupies exactly its own byte count.

Usage:
    python3 tools/embed-files.py
"""

import os, sys

# ── Constants (must match include/fs.h) ──────────────────────────
# 127 file slots — keep in sync with include/fs.h.
MAX_FILES    = 127
MAX_FILENAME = 32
MAX_FILESIZE = 16*1024*1024

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(SCRIPT_DIR)
HOST_DIR    = os.path.join(PROJECT_DIR, 'host-files')
OUTPUT      = os.path.join(PROJECT_DIR, 'cpu', 'embedded_fs.c')

SKIP_FILES  = {'README.txt', 'README.md'}


def hex_row(data: bytes) -> str:
    """Format up to 12 bytes as a C hex literal line."""
    parts = []
    for b in data:
        parts.append(f'0x{b:02x},')
    return ''.join(parts)


def generate():
    # ── Scan host-files/ recursively ────────────────────────────
    # Subfolders are supported (e.g. host-files/icons/): every file
    # is embedded under its basename, flattened into the flat
    # filesystem.  Duplicate basenames are skipped (first wins).
    entries = []
    seen_names = set()
    if os.path.isdir(HOST_DIR):
        for root, dirs, files in os.walk(HOST_DIR):
            # Never descend into hidden dirs (e.g. .originals backups)
            dirs[:] = [d for d in dirs if not d.startswith('.')]
            for name in sorted(files):
                if name.startswith('.') or name in SKIP_FILES:
                    continue
                path = os.path.join(root, name)
                fname = name
                if len(fname) > MAX_FILENAME - 1:
                    fname = fname[:MAX_FILENAME - 1]
                if fname in seen_names:
                    print(f"  ⚠  duplicate name '{fname}' ignored (from {path})")
                    continue
                if len(entries) >= MAX_FILES:
                    print(f"  ⚠  Max {MAX_FILES} files, ignoring '{name}'")
                    continue
                seen_names.add(fname)
                with open(path, 'rb') as fh:
                    raw = fh.read()
                if len(raw) > MAX_FILESIZE:
                    print(f"  ⚠  '{fname}' is {len(raw)} B — truncating to {MAX_FILESIZE}")
                    raw = raw[:MAX_FILESIZE]
                entries.append((fname, raw))

    n = len(entries)

    # ── Build output lines ───────────────────────────────────────
    L = []
    L.append('// cpu/embedded_fs.c — Auto-generated. Do not edit.')
    L.append('// Generated by: tools/embed-files.py')
    L.append(f'// Source dir: {HOST_DIR}')
    L.append('')
    L.append('#include <fs.h>')
    L.append('#include <stdint.h>')
    L.append('')

    if n == 0:
        L.append('void fs_load_embedded(void) {')
        L.append('    // No embedded files — filesystem stays empty.')
        L.append('}')
        L.append('')
    else:
        # ── Per-file exact-size arrays (no padding) ─────
        for idx, (name, raw) in enumerate(entries):
            L.append(f'static const unsigned char _d_{idx}[{len(raw)}] = {{')
            pos = 0
            buf = []
            for b in raw:
                buf.append(f'0x{b:02x},')
                pos += 1
                if pos % 12 == 0:
                    L.append('  ' + ''.join(buf))
                    buf = []
            if buf:
                L.append('  ' + ''.join(buf))
            L.append('};')
            L.append('')

        # ── Pointer-based metadata table ────────────────
        L.append('static const struct {')
        L.append('    const char* name;')
        L.append('    const unsigned char* data;')
        L.append('    int size;')
        L.append(f'}} _embedded[{n}] = {{')
        for idx, (name, raw) in enumerate(entries):
            escaped = name.replace('\\', '\\\\').replace('"', '\\"')
            L.append(f'    {{"{escaped}", _d_{idx}, {len(raw)}}},')
        L.append('};')
        L.append('')

        # ── Init function ───────────────────────────────
        L.append('void fs_load_embedded(void) {')
        L.append(f'    for (int i = 0; i < {n} && file_count < MAX_FILES; i++) {{')
        L.append('        int fi = file_count;')
        L.append('        // Copy name')
        L.append('        int j = 0;')
        L.append('        while (_embedded[i].name[j] && j < MAX_FILENAME - 1) {')
        L.append('            filesystem[fi].name[j] = _embedded[i].name[j];')
        L.append('            j++;')
        L.append('        }')
        L.append("        filesystem[fi].name[j] = '\\0';")
        L.append('        // Point directly to static .rodata -- no heap alloc or copy.')
        L.append('        // content_cap=0 marks buffer as non-heap so file_content_free')
        L.append('        // skips kfree() on these static pointers.')
        L.append('        filesystem[fi].content = (char*)_embedded[i].data;')
        L.append('        filesystem[fi].content_cap = 0;')
        L.append('        filesystem[fi].size = _embedded[i].size;')
        L.append('        filesystem[fi].used = 1;')
        L.append('        file_count++;')
        L.append('    }')
        L.append('}')

    # ── Write file ────────────────────────────────────────────────
    source = '\n'.join(L)
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, 'w') as fh:
        fh.write(source)

    print(f"  ✔  Generated {OUTPUT}  ({len(source)} bytes)")
    if entries:
        print(f"     Embedded {len(entries)} file(s):")
        for name, raw in entries:
            print(f"       {name:32s} {len(raw):4d} bytes")
    else:
        print("     (no files found in host-files/ — empty filesystem)")
    print()


if __name__ == '__main__':
    generate()
