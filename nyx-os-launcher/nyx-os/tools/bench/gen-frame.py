#!/usr/bin/env python3
"""gen-frame.py — Regenerate tools/bench/frame.h from host-files/jace.mp4.

Pulls 3 spread JPEG frames (first, middle, last) out of the MJPEG-in-MP4
the kernel actually plays and emits them as C arrays, so the TCG decode
benchmark (tools/bench/, `make bench`) measures the real frames rather
than synthetic data.  Re-run whenever jace.mp4 is re-transcoded.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MP4 = os.path.join(HERE, '..', '..', 'host-files', 'jace.mp4')
OUT = os.path.join(HERE, 'frame.h')


def extract_frames(path):
    with open(path, 'rb') as fh:
        f = fh.read()
    frames = []
    pos = 0
    while True:
        s = f.find(b'\xff\xd8', pos)
        if s < 0:
            break
        e = f.find(b'\xff\xd9', s)
        if e < 0:
            break
        frames.append(f[s:e + 2])
        pos = e + 2
    return frames


def main():
    if not os.path.exists(MP4):
        print(f'  ✗  {MP4} not found — run the transcode first')
        return 1
    frames = extract_frames(MP4)
    if len(frames) < 3:
        print(f'  ✗  only {len(frames)} frames — need at least 3')
        return 1
    idxs = [0, len(frames) // 2, len(frames) - 1]

    out = [
        '// Auto-generated by tools/bench/gen-frame.py — do not edit.',
        '// 3 spread JPEG frames extracted from host-files/jace.mp4 (the',
        '// MJPEG the kernel video player actually decodes).',
        '#ifndef BENCH_FRAME_H',
        '#define BENCH_FRAME_H',
        '#include <stdint.h>',
        '',
    ]
    for i, fi in enumerate(idxs):
        d = frames[fi]
        hexs = ','.join('0x%02x' % b for b in d)
        out.append(f'static const uint8_t bench_f{i}[] = {{{hexs}}};')
    out.append('')
    out.append('static const uint8_t* const bench_frames[3] = '
               '{ bench_f0, bench_f1, bench_f2 };')
    out.append('static const int bench_lens[3] = {%d, %d, %d};'
               % tuple(len(frames[i]) for i in idxs))
    out.append('')
    out.append('#endif')
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(out))
    print(f'  ✔  frame.h regenerated: frames {idxs} '
          f'({[len(frames[i]) for i in idxs]} bytes each)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
